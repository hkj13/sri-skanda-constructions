// Extracts the Jost letterforms used by the wordmark as plain SVG path data,
// so every logo lockup is pure outlines and never depends on a font loading.
//
//   node scripts/build-wordmark-glyphs.mjs
//
// Output: src/brand/jost-glyphs.ts (generated, committed).
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import opentype from "opentype.js";

const require = createRequire(import.meta.url);
const WEIGHTS = [300, 400, 500, 600, 700];
const LINES = ["SRI SKANDA", "CONSTRUCTIONS"];
const CHARS = [...new Set(LINES.join("").replace(/ /g, ""))].sort();

const out = {};
for (const weight of WEIGHTS) {
  const file = require.resolve(
    `@fontsource/jost/files/jost-latin-${weight}-normal.woff`,
  );
  const buf = readFileSync(file);
  const font = opentype.parse(
    buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength),
  );
  const upm = font.unitsPerEm;
  const glyphs = {};
  for (const ch of CHARS) {
    const g = font.charToGlyph(ch);
    glyphs[ch] = {
      d: g.getPath(0, 0, upm).toPathData(1),
      adv: g.advanceWidth,
      lsb: Math.round(g.getMetrics().xMin),
      rsb: Math.round(g.advanceWidth - g.getMetrics().xMax),
    };
  }
  const kern = {};
  for (const line of LINES) {
    for (const word of line.split(" ")) {
      for (let i = 0; i < word.length - 1; i++) {
        const pair = word[i] + word[i + 1];
        const k = font.getKerningValue(
          font.charToGlyph(pair[0]),
          font.charToGlyph(pair[1]),
        );
        if (k) kern[pair] = k;
      }
    }
  }
  out[weight] = {
    unitsPerEm: upm,
    capHeight: font.tables.os2.sCapHeight,
    space: font.charToGlyph(" ").advanceWidth,
    glyphs,
    kern,
  };
}

const banner =
  "// GENERATED by scripts/build-wordmark-glyphs.mjs. Do not edit by hand.\n" +
  "// Jost is licensed under the SIL Open Font License 1.1 (see CREDITS.md).\n";
const body =
  "export type GlyphOutline = { d: string; adv: number; lsb: number; rsb: number };\n" +
  "export type WeightOutlines = {\n" +
  "  unitsPerEm: number;\n  capHeight: number;\n  space: number;\n" +
  "  glyphs: Record<string, GlyphOutline>;\n  kern: Record<string, number>;\n};\n" +
  "export type WordmarkWeight = 300 | 400 | 500 | 600 | 700;\n\n" +
  "export const JOST_GLYPHS: Record<WordmarkWeight, WeightOutlines> = " +
  JSON.stringify(out, null, 1) +
  ";\n";
writeFileSync(new URL("../src/brand/jost-glyphs.ts", import.meta.url), banner + body);
console.log("wrote src/brand/jost-glyphs.ts", CHARS.join(""));
for (const w of WEIGHTS) console.log(w, out[w].unitsPerEm, out[w].capHeight, out[w].space, out[w].kern);
